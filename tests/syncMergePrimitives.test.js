// Characterisation of the tracking-merge primitives behind SyncEngine.mergeTrackingProgress: sessions and their
// tombstones, running totals, fractional-stitch pairs, the per-day stitch log, parking markers, the work area and
// the lifecycle dates.
//
// tests/support/syncMergePrimitiveCases.js drives the real SyncEngine facade with representative, empty, legacy and
// malformed inputs and records the returned value, any error, whether the arguments were left alone and which
// results are the objects that were passed in. The record is compared with
// tests/fixtures/syncMergePrimitives.golden.json, which was generated by reports/cleanup-18/capture-golden.cjs on
// the code as it was before these helpers moved out of sync-engine.js. The golden file is evidence of preserved
// behaviour: do not regenerate it to make a failure go away.

const fs = require('fs');
const pako = require('pako');

global.window = global.window || {};
global.localStorage = (() => {
  const store = {};
  return {
    getItem(k) { return store[k] !== undefined ? store[k] : null; },
    setItem(k, v) { store[k] = String(v); },
    removeItem(k) { delete store[k]; },
    clear() { Object.keys(store).forEach(k => delete store[k]); }
  };
})();
global.pako = pako;
global.indexedDB = undefined;
global.ProjectStorage = { listProjects: async () => [], get: async () => null, save: async p => p.id };

eval(fs.readFileSync('./sync-engine.js', 'utf8'));
const SE = global.SyncEngine || global.window.SyncEngine;

const cases = require('./support/syncMergePrimitiveCases');
const golden = require('./fixtures/syncMergePrimitives.golden.json');

describe('tracking-merge primitives keep their recorded behaviour', () => {
  const actual = cases.run(SE);

  test('the battery covers exactly the recorded cases', () => {
    expect(Object.keys(actual).sort()).toEqual(Object.keys(golden).sort());
  });

  test.each(Object.keys(golden))('%s', (name) => {
    expect(actual[name]).toEqual(golden[name]);
  });
});

describe('contracts worth reading without the golden file', () => {
  const s = (id, start, extra) => Object.assign({ id, start, date: start.slice(0, 10) }, extra);

  test('sessions: a tombstone on either side removes the record from both', () => {
    const merged = SE.mergeSessions(
      [s('a', '2026-07-01T00:00:00Z'), s('b', '2026-07-02T00:00:00Z')],
      [s('a', '2026-07-01T00:00:00Z'), s('c', '2026-07-03T00:00:00Z')], ['a']);
    expect(merged.map(x => x.id)).toEqual(['b', 'c']);
  });

  test('sessions: the later editedAt wins; a record never edited loses to an edited one', () => {
    const local = [s('a', '2026-07-01T00:00:00Z', { note: 'local' })];
    const remote = [s('a', '2026-07-01T00:00:00Z', { note: 'remote', editedAt: '2026-08-01T00:00:00Z' })];
    expect(SE.mergeSessions(local, remote, [])[0].note).toBe('remote');
    expect(SE.mergeSessions(remote, local, [])[0].note).toBe('remote');
  });

  test('sessions: returns the callers\' own records, not copies, and does not touch the inputs', () => {
    const l = s('a', '2026-07-01T00:00:00Z'), r = s('b', '2026-07-02T00:00:00Z');
    const localList = [l], remoteList = [r];
    const merged = SE.mergeSessions(localList, remoteList, []);
    expect(merged[0]).toBe(l);
    expect(merged[1]).toBe(r);
    expect(localList).toEqual([l]);
    expect(remoteList).toEqual([r]);
  });

  test('done: returns the lone array it was given, and a new union array otherwise', () => {
    const only = [1, 0];
    expect(SE.mergeDoneArrays(null, only, 2)).toBe(only);
    expect(SE.mergeDoneArrays(only, null, 2)).toBe(only);
    const union = SE.mergeDoneArrays([1, 0], [0, 1], 2);
    expect(union).toEqual([1, 1]);
    expect(union).not.toBe(only);
  });

  test('pairs: empty inputs return the caller\'s own array; details are copied, not shared', () => {
    const empty = [];
    expect(SE.mergeIndexedPairs(empty, [])).toBe(empty);
    const detail = { deep: [1] };
    const merged = SE.mergeIndexedPairs([[1, detail]], []);
    expect(merged[0][1]).toEqual(detail);
    expect(merged[0][1]).not.toBe(detail);
  });

  test('stitch log: per-day maximum, sorted by date, never a sum', () => {
    expect(SE.mergeStitchLogs(
      [{ date: '2026-07-02', count: 5 }, { date: '2026-07-01', count: 9 }],
      [{ date: '2026-07-01', count: 4 }, { date: '2026-07-02', count: 8 }]))
      .toEqual([{ date: '2026-07-01', count: 9 }, { date: '2026-07-02', count: 8 }]);
  });
});
